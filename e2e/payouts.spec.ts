import { expect, test } from "./fixtures"

test.describe("Cash-outs and moving coins", () => {
  test("parent moves coins into a goal, cashes out the full jar and the goal is achieved @mobile", async ({ api, shell, authedPage: page }) => {
    const kid = await api.addKid({ name: "Aarav" })
    await api.addGoal(kid.id, { name: "Bike", emoji: "🚲", targetAmount: 100 })
    await api.earn(kid.id, { kind: "EXTRA", amount: 150, note: "Birthday" })
    await shell.goto(`/kids/${kid.id}`)
    const dialog = page.getByRole("dialog")
    const balance = page.getByRole("region", { name: "Balance" })

    await page.getByRole("button", { name: "Move coins" }).click()
    await expect(dialog.getByLabel("From")).toHaveValue("")
    await dialog.getByLabel("To").selectOption({ label: "🚲 Bike (0 Kid Coins)" })
    await dialog.getByLabel("Amount (Kid Coins)").fill("100")
    await dialog.getByRole("button", { name: "Move" }).click()
    await expect(dialog).toBeHidden()
    const bike = page.getByRole("article", { name: "Bike" })
    await expect(bike).toContainText("Ready!")
    await expect(balance.getByLabel("Wallet balance")).toContainText("50 Kid Coins")
    await expect(page.getByText("Moved to Bike").first()).toBeVisible()

    await page.getByRole("button", { name: "Cash out" }).click()
    await dialog.getByLabel("Take from").selectOption({ label: "🚲 Bike (100 Kid Coins)" })
    await dialog.getByLabel("Amount (Kid Coins)").fill("100")
    await dialog.getByLabel("What it's for").fill("Bought the bike")
    await dialog.getByRole("button", { name: "Cash out" }).click()
    await expect(dialog).toBeHidden()
    await expect(bike).toContainText("Achieved")
    await expect(bike).toContainText("Saved 100 Kid Coins and cashed out")
    await expect(bike.getByRole("button", { name: /Edit/ })).toHaveCount(0)
    await expect(balance).toContainText("50 Kid Coins")
    await expect(page.getByText("Cash out · Bought the bike").first()).toBeVisible()
    // An achieved goal no longer appears as a destination
    await page.getByRole("button", { name: "Extra earning" }).click()
    await expect(dialog.getByLabel("Add to").locator("option")).toHaveText(["Wallet"])
  })

  test("cash-out can't take more than the Wallet holds, and keeps what was typed @mobile", async ({ api, shell, authedPage: page }) => {
    const kid = await api.addKid({ name: "Meera" })
    await api.earn(kid.id, { kind: "EXTRA", amount: 50, note: "Gift" })
    await shell.goto(`/kids/${kid.id}`)
    const dialog = page.getByRole("dialog")
    await page.getByRole("button", { name: "Cash out" }).click()
    await dialog.getByLabel("Amount (Kid Coins)").fill("51")
    await dialog.getByLabel("What it's for").fill("x".repeat(60))
    await dialog.getByRole("button", { name: "Cash out" }).click()
    await expect(dialog).toContainText("Only 50 Kid Coins in the Wallet")
    await expect(dialog.getByLabel("Amount (Kid Coins)")).toHaveValue("51")
    expect(await dialog.evaluate((d) => d.scrollWidth <= d.clientWidth)).toBe(true)
    await dialog.getByLabel("Amount (Kid Coins)").fill("50")
    await dialog.getByRole("button", { name: "Cash out" }).click()
    await expect(dialog).toBeHidden()
    await expect(page.getByRole("region", { name: "Balance" })).toContainText("0 Kid Coins")
    await expect(page.getByRole("button", { name: "Cash out" })).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  })
})
